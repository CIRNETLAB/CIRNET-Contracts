// JSON Schema is shape authority. This script only orchestrates pinned tools.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import {createRequire} from 'node:module'
import {pathToFileURL} from 'node:url'
const toolRoot=process.argv[4]
if(!toolRoot)throw Error('Explicit installed Node codegen tool directory required')
const require=createRequire(resolve(toolRoot,'package.json'))
const Ajv2020=(await import(pathToFileURL(require.resolve('ajv/dist/2020.js')).href)).default
const standalone=(await import(pathToFileURL(require.resolve('ajv/dist/standalone/index.js')).href)).default
const {compile}=await import(pathToFileURL(require.resolve('json-schema-to-typescript')).href)
const {build}=await import(pathToFileURL(require.resolve('esbuild')).href)

const [input, output] = process.argv.slice(2)
if (!input || !output) throw new Error('Usage: node generate-contracts.mjs BUNDLE.json OUTPUT')
const profiles = JSON.parse(await readFile(input, 'utf8'))
const schema = profiles.transport
const names = Object.keys(schema.$defs)
// Synchronous document editing and authentication must not load complete API,
// assignment, capture and realtime registries. Other workflows prepare a profile.
const documentNames=['AnySupportedCircuitGraph','CircuitGraph','MemoryImage','LeadSettings','WireVisual','SignalDomainNamespace','LabelPropertiesV1','FlexibleMountV1','FlexibleMountV2']
const eagerNames={
  editor:documentNames,
  structural:['AnySupportedCircuitGraph','SignalDomainNamespace','LabelPropertiesV1','ComponentDesignPropertiesV1'],
  transport:['SignalDomainNamespace','LabelPropertiesV1','HealthResponse','SessionView','LoginRequest','LogoutRequest','GuestClaimRequest','UserView','UserCreate','UserUpdate','ErrorEnvelope','AnySupportedAssignmentDefinition','AssignmentDefinition','AssignmentDefinitionV2','DetectedTopologyGraph','CaptureConfiguration','ClockConfiguration','GeneratorConfiguration','TestVector','PublicStationCapabilities','ExperimentCreate'],
}
await mkdir(output, { recursive: true })
await writeFile(resolve(output,'publicContractNames.ts'),'// Generated public-only registry identity. DO NOT EDIT.\nexport const publicContractNames = '+JSON.stringify(names)+' as const\n','utf8')
for (const [profile, schema] of Object.entries(profiles)) {
const ajv = new Ajv2020({ strict: true, strictRequired: false, strictTypes: false,
  allErrors: true, coerceTypes: false, useDefaults: false, removeAdditional: false,
  inlineRefs: false, code: { source: true, lines: true, esm: true }, loopRequired: 200 })
ajv.addSchema(schema)
const exports = Object.fromEntries(names.map(name => [name, `${schema.$id}#/$defs/${name}`]))
for (const uri of Object.values(exports)) if (!ajv.getSchema(uri)) throw new Error(`Unresolved export ${uri}`)
const source = standalone.default ? standalone.default(ajv, exports) : standalone(ajv, exports)
// Bundle Ajv's small static helpers as ESM. No runtime Function/eval or Ajv
// compiler is shipped to the browser; browser CSP can disallow dynamic code.
const bundled = await build({ absWorkingDir: toolRoot, stdin: { contents: source, resolveDir: toolRoot, sourcefile: 'validators.mjs' },
  bundle: true, platform: 'browser', format: 'esm', write: false, legalComments: 'none', minify: false })
const stem = profile === 'transport' ? 'validators' : `validators.${profile}`
const declarations = `// Generated. DO NOT EDIT.\nimport type { ContractMap } from './dto'\nexport interface ValidationIssue { instancePath: string; keyword: string; message?: string; params: Record<string, unknown> }\nexport interface Validator<T> { (value: unknown): value is T; errors?: ValidationIssue[] | null }\n${names.map(name=>`export const ${name}: Validator<ContractMap['${name}']>`).join('\n')}\n`
await writeFile(resolve(output, `${stem}.js`), '// Generated by pinned Ajv 2020. DO NOT EDIT.\n'+bundled.outputFiles[0].text, 'utf8')
await writeFile(resolve(output, `${stem}.d.ts`), declarations, 'utf8')
const eager=Object.fromEntries(eagerNames[profile].map(name=>[name,exports[name]??(()=>{throw new Error(`Unknown eager contract ${name}`)})()]))
const eagerSource=standalone.default?standalone.default(ajv,eager):standalone(ajv,eager)
const eagerBundle=await build({absWorkingDir:toolRoot,stdin:{contents:eagerSource,resolveDir:toolRoot,sourcefile:'validators-core.mjs'},bundle:true,platform:'browser',format:'esm',write:false,legalComments:'none',minify:false})
await writeFile(resolve(output,`${stem}.core.js`),'// Generated by pinned Ajv 2020. DO NOT EDIT.\n'+eagerBundle.outputFiles[0].text,'utf8')
await writeFile(resolve(output,`${stem}.core.d.ts`),declarations.split('\n').filter(line=>!line.startsWith('export const ')||eagerNames[profile].some(name=>line.startsWith(`export const ${name}:`))).join('\n'),'utf8')
}
const dto = await compile({ ...schema, title: 'ContractMap' }, 'ContractMap', { bannerComment: '// Generated from contracts/manifest.json by scripts/generate_contracts.py. DO NOT EDIT.',
  unknownAny: true, unreachableDefinitions: true, ignoreMinAndMaxItems: true,
  style: { singleQuote: true, semi: false, tabWidth: 2 }, additionalProperties: true })
await writeFile(resolve(output, 'dto.ts'), dto.replaceAll('\r\n','\n'), 'utf8')
