"""Generate standalone package outputs from canonical resources and frozen OpenAPI.

Remote owns route export. Consumers use export_artifacts() to compare/export
the immutable compatibility projections embedded in the installed artifact.
"""
import argparse
import hashlib
import json
from pathlib import Path
import pprint
import shutil
import subprocess
import sys
from tempfile import TemporaryDirectory
import uuid

from contracts.registry import check_manifest, entries, load_schema, schema_bundle, validate_contract
from contracts.resources import generated_artifacts, resource_json
from contracts.codegen.openapi import operation_bindings

ROOT = Path(__file__).resolve().parents[2]
CONTRACTS = Path(__file__).resolve().parents[1]


def capture_layout_outputs():
    layout = resource_json('capture/layout.json')
    validate_contract('NCAPLayout', layout)
    return {
        'apps/web/src/contracts/generated/captureLayout.ts': '// Generated by scripts/generate_contracts.py from contracts/capture/layout.json.\nexport const captureLayout = '+json.dumps(layout, indent=2)+' as const\n',
        'contracts/boundary/capture_layout.py': '# Generated by scripts/generate_contracts.py from contracts/capture/layout.json.\nCAPTURE_LAYOUT = '+pprint.pformat(layout, sort_dicts=False, width=100)+'\n',
    }


def publish_artifacts(artifacts, output_root):
    """Publish after every generator succeeds; roll back ordinary I/O failure."""
    output_root = Path(output_root).resolve()
    identity = uuid.uuid4().hex
    pending, originals, replaced = {}, {}, []
    try:
        for relative, source in artifacts.items():
            target = (output_root / relative).resolve()
            if not target.is_relative_to(output_root):
                raise ValueError(f'Artifact escapes output root: {relative}')
            target.parent.mkdir(parents=True, exist_ok=True)
            originals[target] = target.read_bytes() if target.exists() else None
            candidate = target.with_name(target.name+'.'+identity+'.new')
            pending[target] = candidate
            shutil.copyfile(source, candidate)
        for target, candidate in pending.items():
            candidate.replace(target)
            replaced.append(target)
    except Exception:
        for target in reversed(replaced):
            original = originals[target]
            if original is None:
                target.unlink()
            else:
                rollback = target.with_name(target.name+'.'+identity+'.rollback')
                rollback.write_bytes(original)
                rollback.replace(target)
        raise
    finally:
        for candidate in pending.values():
            if candidate.exists():
                candidate.unlink()


def _publish_bytes(artifacts, output_root, check):
    output_root = Path(output_root).resolve()
    stale = [path for path, value in artifacts.items()
             if not (output_root/path).is_file() or (output_root/path).read_bytes() != value]
    if check:
        if stale:
            raise SystemExit('Stale contract artifacts:\n'+'\n'.join(stale))
        return
    with TemporaryDirectory(prefix='netcircuit-publish-') as temporary:
        sources = {}
        for relative, value in artifacts.items():
            source = Path(temporary)/relative
            source.parent.mkdir(parents=True, exist_ok=True)
            source.write_bytes(value)
            sources[Path(relative)] = source
        publish_artifacts(sources, output_root)


def export_artifacts(*, output_root, check=False):
    """Export installed projections to an explicit destination; never regenerate."""
    _publish_bytes(generated_artifacts(), output_root, check)


def generate(*, check=False, output_root=ROOT, openapi=None, node_tools=None):
    check_manifest()
    document = json.loads(Path(openapi).read_text(encoding='utf-8')) if openapi else resource_json('api/openapi.json')
    node_tools = Path(node_tools).resolve() if node_tools else ROOT/'packages/public-sdk'
    with TemporaryDirectory(prefix='netcircuit-contracts-codegen-') as temporary:
        stage = Path(temporary)
        bundle = stage/'public.json'
        bundles = {profile: schema_bundle(public_only=True, profile=profile)
                   for profile in ('structural', 'editor', 'transport')}
        bundle.write_text(json.dumps(bundles, indent=2)+'\n', encoding='utf-8')
        generated = stage/'contracts/browser/generated'
        subprocess.run(['node', str(CONTRACTS/'codegen/generate_typescript_contracts.mjs'), str(bundle), str(generated), str(node_tools)], check=True)
        from contracts.codegen.generate_python_contracts import generate as generate_python
        python = stage/'contracts/boundary/models.py'
        generate_python(python)
        artifacts = {path.relative_to(stage).as_posix(): path.read_bytes()
                     for path in stage.rglob('*') if path.is_file() and path != bundle}
        # Preserve the established generated header: the document is still owned
        # by FastAPI registrations, now supplied through the reviewed handoff.
        artifacts['contracts/browser/generated/operations.ts'] = operation_bindings(document).encode('utf-8')
        artifacts['contracts/api/openapi.json'] = (json.dumps(document, indent=2, sort_keys=True)+'\n').encode('utf-8')
        for path, value in capture_layout_outputs().items():
            path = path.replace('apps/web/src/contracts/generated/', 'contracts/browser/generated/')
            artifacts[path] = value.encode('utf-8')
        lab_entries = [entry for entry in entries() if entry['path']=='contracts/physical-lab/lab.schema.json' and entry['visibility']=='public']
        lab = load_schema('https://netcircuit.local/contracts/physical-lab/1.0/lab.schema.json')
        lab['$defs'] = {entry['id']: lab['$defs'][entry['id']] for entry in lab_entries}
        artifacts['contracts/browser/data/labContracts.json'] = (json.dumps(lab, indent=2)+'\n').encode('utf-8')
        artifacts['contracts/browser/types/lab.ts'] = ('// Generated by scripts/generate_contracts.py; edit canonical contracts.\nexport type { '+', '.join(entry['id'] for entry in lab_entries)+" } from '../contracts/generated/dto'\n").encode('utf-8')
        for profile, value in bundles.items():
            artifacts['contracts/browser/schemas/'+profile+'.json'] = (json.dumps(value, indent=2)+'\n').encode('utf-8')
        profiles = resource_json('profiles.json')
        public_names = set(bundles['structural']['$defs'])
        for profile in profiles['profiles'].values():
            profile['definitions'] = {name: value for name, value in profile['definitions'].items() if name in public_names}
        artifacts['contracts/browser/schemas/profiles.json'] = (json.dumps(profiles, indent=2)+'\n').encode('utf-8')
        from contracts.codegen.sync_editor_catalog import catalog_outputs, catalog_source
        catalogs, _, _ = catalog_outputs()
        artifacts.update(catalogs)
        for path in (CONTRACTS/'fixtures').glob('*.json'):
            value = json.loads(path.read_text(encoding='utf-8'))
            if isinstance(value, dict) and 'cases' in value:
                value['cases'] = [case for case in value['cases']
                                  if (case.get('contract') is None or case['contract'] in public_names)
                                  and not case.get('internal_only')]
            artifacts['contracts/browser/fixtures/'+path.name] = (json.dumps(value, indent=2)+'\n').encode('utf-8')
        # Corpus files without a named boundary contain only public graph,
        # geometry or capture descriptors; retain their original fixture bytes.
        for folder in ('design-models/fixtures', 'fixtures/capture'):
            for path in (CONTRACTS/folder).glob('*.json'):
                name = 'capture-'+path.name if folder=='fixtures/capture' else path.name
                artifacts['contracts/browser/fixtures/'+name] = path.read_bytes()
        canonical = sorted({entry['path'] for entry in entries()} | {'contracts/profiles.json', 'contracts/manifest.json'})
        source = hashlib.sha256()
        for path in canonical:
            value = artifacts.get(path)
            if value is None: value = (ROOT/path).read_bytes()
            source.update(path.encode('utf-8')+b'\0'+value.replace(b'\r\n',b'\n')+b'\0')
        catalog_root = catalog_source()
        for path in sorted(catalog_root.rglob('*.json')):
            identity = 'device-library/'+path.relative_to(catalog_root).as_posix()
            source.update(identity.encode('utf-8')+b'\0'+path.read_bytes().replace(b'\r\n',b'\n')+b'\0')
        public = hashlib.sha256(json.dumps(bundles, sort_keys=True, separators=(',', ':')).encode('utf-8')).hexdigest()
        fingerprints = {'canonical_source_sha256': source.hexdigest(), 'public_schema_sha256': public,
                        'openapi_sha256': hashlib.sha256(artifacts['contracts/api/openapi.json']).hexdigest()}
        artifacts['contracts/fingerprints.json'] = (json.dumps(fingerprints, indent=2)+'\n').encode('utf-8')
        _publish_bytes(artifacts, output_root, check)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    parser.add_argument('--openapi', type=Path)
    parser.add_argument('--node-tools', type=Path)
    options = parser.parse_args()
    generate(check=options.check, output_root=options.output_root, openapi=options.openapi, node_tools=options.node_tools)


if __name__ == '__main__':
    main()
